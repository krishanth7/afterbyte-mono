    if any(len(row)!=len(rows[0]) or set(row)-set('.#') for row in rows):
        raise ValueError('Invalid matrix '+repr(ch))
    GLYPHS[ch]={'character':ch,'unicode':ord(ch),'top':top,'left':left,'rows':rows}


