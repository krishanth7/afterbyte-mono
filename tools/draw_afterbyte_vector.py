def add(ch,*paths,solids=None,stroke=64):
    G[ch]={'character':ch,'unicode':ord(ch),'paths':list(paths),'solids':solids or [],'stroke':stroke}


def shifted(record,dx=0,dy=0):
    out=copy.deepcopy(record)
    for path in out['paths']:
        for command in path:
            for i in range(1,len(command),2):command[i]+=dx;command[i+1]+=dy
    for polygon in out['solids']:
        for point in polygon:point[0]+=dx;point[1]+=dy
    return out


def oval(x0,y0,x1,y1):
    # Rounded rectangular bowl; tangent control points, no octagonal corners.
    radius=min(125,(x1-x0)/2,(y1-y0)/2)
    k=0.55228475; r=radius
    return [['M',x0+r,y0],['L',x1-r,y0],['C',x1-r+k*r,y0,x1,y0+r-k*r,x1,y0+r],
            ['L',x1,y1-r],['C',x1,y1-r+k*r,x1-r+k*r,y1,x1-r,y1],
            ['L',x0+r,y1],['C',x0+r-k*r,y1,x0,y1-r+k*r,x0,y1-r],
            ['L',x0,y0+r],['C',x0,y0+r-k*r,x0+r-k*r,y0,x0+r,y0],['Z']]


